/// `newComputePipelineStateWithFunction:error:`: compiles `function` into a compute pipeline
/// state, translating its AIR and compiling the SPIR-V for the adopted device.
///
/// Returns NULL on failure, with [`sweetmtl_last_error`] saying why (an unsupported capability, a
/// translation refusal, a compile failure).
///
/// # Safety
///
/// `device` is a live device handle and `function` is a live function of it.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_device_new_compute_pipeline(
    device: *mut SweetMTLDevice,
    function: *mut SweetMTLFunction,
) -> *mut SweetMTLComputePipeline {
    guard(ptr::null_mut(), || {
        let Some(state) = (unsafe { SweetMTLDevice::state(device) }) else {
            set_last_error("sweetmtl_device_new_compute_pipeline: device is NULL");
            return ptr::null_mut();
        };
        let Some(function) = (unsafe { SweetMTLFunction::state(function) }) else {
            set_last_error("sweetmtl_device_new_compute_pipeline: function is NULL");
            return ptr::null_mut();
        };
        let options = PipelineOptions::default();
        match state
            .device()
            .new_compute_pipeline_state_with_function(&function.function, &options)
        {
            Ok(pipeline) => SweetMTLComputePipeline::make(ComputePipelineState(pipeline)),
            Err(error) => {
                set_last_error(format!("new_compute_pipeline_state failed: {error}"));
                ptr::null_mut()
            }
        }
    })
}

