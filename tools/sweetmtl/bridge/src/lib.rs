/// A library from **AIR bitcode** — what `llvm-as` writes from a `.ll` (a raw module or a bitcode
/// wrapper), translated by `metal2vulkan` rather than read as a metallib.
///
/// Metal has no counterpart (`newLibraryWithData:` takes metallibs alone): this is the bridge's
/// door for the translator's own fixtures, and what the C test drives
/// (`llvm-as tests/…/runtime_examples.ll`).
///
/// Returns NULL on failure, with [`sweetmtl_last_error`] saying why.
///
/// # Safety
///
/// `device` is a live device handle, and `bytes` names `length` readable bytes.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_device_new_library_with_air(
    device: *mut SweetMTLDevice,
    bytes: *const u8,
    length: u64,
) -> *mut SweetMTLLibrary {
    guard(ptr::null_mut(), || {
        let Some(state) = (unsafe { SweetMTLDevice::state(device) }) else {
            set_last_error("sweetmtl_device_new_library_with_air: device is NULL");
            return ptr::null_mut();
        };
        let bytes = match unsafe { bytes_arg(bytes, length, "bytes") } {
            Ok(bytes) => bytes,
            Err(message) => {
                set_last_error(message);
                return ptr::null_mut();
            }
        };
        match metal2vulkan::library::Library::from_air(bytes) {
            Ok(library) => {
                let library = state.device().new_library_with_compile_library(library);
                SweetMTLLibrary::make(LibraryState { library })
            }
            Err(error) => {
                set_last_error(format!("Library::from_air({length} bytes) failed: {error}"));
                ptr::null_mut()
            }
        }
    })
}

