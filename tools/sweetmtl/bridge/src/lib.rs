/// `waitUntilCompleted`: waits for the committed command buffer's work to complete.
///
/// `timeout_ms` is 0 to wait indefinitely, or a number of milliseconds after which the call gives
/// up (nonzero return with `"timed out"` in [`sweetmtl_last_error`]). A command buffer that failed
/// on the GPU returns nonzero, with what the runtime knows of the failure in the error.
///
/// Returns 0 on success and nonzero on failure.
///
/// # Safety
///
/// `command_buffer` is a live, committed command buffer handle.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_command_buffer_wait_until_completed(
    command_buffer: *mut SweetMTLCommandBuffer,
    timeout_ms: u64,
) -> c_int {
    guard(-1, || {
        let Some(state) = (unsafe { SweetMTLCommandBuffer::state(command_buffer) }) else {
            set_last_error("sweetmtl_command_buffer_wait_until_completed: command buffer is NULL");
            return -1;
        };
        if timeout_ms == 0 {
            return match state.command_buffer.wait_until_completed() {
                Ok(()) => 0,
                Err(error) => {
                    set_last_error(format!("wait_until_completed failed: {error}"));
                    -1
                }
            };
        }
        match state
            .command_buffer
            .wait_until_completed_for(Duration::from_millis(timeout_ms))
        {
            Ok(()) => 0,
            Err(_timed_out) => {
                set_last_error(format!(
                    "wait_until_completed timed out after {timeout_ms} ms"
                ));
                -1
            }
        }
    })
}

/// `MTLCommandBuffer.status`, as Metal's own raw values: 0 not enqueued, 1 enqueued, 2 committed,
/// 3 scheduled, 4 completed, 5 error. Returns -1 for a NULL handle.
///
/// # Safety
///
/// `command_buffer` is a live command buffer handle.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_command_buffer_status(
    command_buffer: *mut SweetMTLCommandBuffer,
) -> c_int {
    guard(-1, || {
        match unsafe { SweetMTLCommandBuffer::state(command_buffer) } {
            Some(state) => state.command_buffer.status().raw() as c_int,
            None => {
                set_last_error("sweetmtl_command_buffer_status: command buffer is NULL");
                -1
            }
        }
    })
}

/// The `MTLCommandBufferStatus` a value of [`sweetmtl_command_buffer_status`] stands for, for a C
/// switch that would rather name them.
#[no_mangle]
pub extern "C" fn sweetmtl_command_buffer_status_name(status: c_int) -> *const c_char {
    match status {
        0 => c"NotEnqueued".as_ptr(),
        1 => c"Enqueued".as_ptr(),
        2 => c"Committed".as_ptr(),
        3 => c"Scheduled".as_ptr(),
        4 => c"Completed".as_ptr(),
        5 => c"Error".as_ptr(),
        _ => c"Unknown".as_ptr(),
    }
}

/// `CommandBuffer::status` is also the bridge's way to tell a completed command buffer from a
/// failed one: nonzero where the status is [`CommandBufferStatus::Completed`]. For the C test.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_command_buffer_completed(
    command_buffer: *mut SweetMTLCommandBuffer,
) -> c_int {
    guard(0, || match unsafe { SweetMTLCommandBuffer::state(command_buffer) } {
        Some(state) => c_int::from(state.command_buffer.status() == CommandBufferStatus::Completed),
        None => {
            set_last_error("sweetmtl_command_buffer_completed: command buffer is NULL");
            0
        }
    })
}
