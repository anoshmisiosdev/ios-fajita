/// `MTLBuffer.contents`: the CPU address of the buffer's bytes, or NULL for private storage (the
/// bridge makes none yet). Reading or writing through it while the GPU writes those bytes is a
/// data race, as in Metal.
///
/// # Safety
///
/// `buffer` is a live buffer handle, and the caller respects the race above.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_buffer_contents(buffer: *mut SweetMTLBuffer) -> *mut c_void {
    guard(ptr::null_mut(), || {
        match unsafe { SweetMTLBuffer::state(buffer) } {
            Some(state) => match state.buffer.contents() {
                Some(contents) => contents.as_ptr().cast(),
                None => {
                    set_last_error("sweetmtl_buffer_contents: the buffer has no CPU address");
                    ptr::null_mut()
                }
            },
            None => {
                set_last_error("sweetmtl_buffer_contents: buffer is NULL");
                ptr::null_mut()
            }
        }
    })
}

