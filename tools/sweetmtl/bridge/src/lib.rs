//! The SweetMTL bridge: a stable C ABI over [`metal2vulkan`](https://github.com/steelbrain/metal2vulkan)'s
//! runtime, for the Objective-C `SweetMTLDevice` classes at `tools/sweetmtl/SweetMTLDevice.m`.
//!
//! The bridge is the layer between `Metal.framework`'s driver interface and the translator: the
//! Objective-C device classes call these functions, and each one drives the runtime's Metal-shaped
//! objects (buffers, libraries, functions, compute pipelines, command queues and buffers, compute
//! encoders) on the Vulkan device the bridge opened on a bare Mesa ICD.
//!
//! # The shape of the ABI
//!
//! - Objects are **opaque pointers** to `#[repr(C)]` handles that own the runtime object. No Rust
//!   type crosses the boundary: the header (`include/sweetmtl_bridge.h`, generated by cbindgen)
//!   declares each handle as `typedef struct { void *_state; } SweetMTL…;`.
//! - Every failing call **records a message** in a per-thread slot; a call that returns a pointer
//!   returns NULL, and one that returns `int` returns nonzero. [`sweetmtl_last_error`] reads the
//!   slot. It is valid until the same thread's next failing call.
//! - A panic never crosses the boundary: every entry point runs inside
//!   [`catch_unwind`](std::panic::catch_unwind) and answers as a failure.
//! - Ownership is explicit, as in Metal: every `sweetmtl_*_new…` returns a handle the caller owns
//!   and releases with the matching `sweetmtl_*_release`. **Release every object before the device
//!   it came from**: the runtime's objects are made from the `VkDevice` the device handle owns.
//!
//! # The first milestone
//!
//! Compute only: init, buffers, libraries and functions, compute pipelines, command queues and
//! command buffers, and compute encoders. Render, textures, samplers, argument buffers, events and
//! the rest of Metal come later, and so do the extension features of the enable vocabulary (see
//! [`backend`]'s module docs and the crate README).

