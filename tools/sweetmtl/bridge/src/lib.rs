/// `newBufferWithLength:options:` in shared storage: the buffer's bytes are in CPU-visible memory,
/// so [`sweetmtl_buffer_contents`] is its pointer (the bridge never makes a private buffer: it has
/// no way to copy to one yet).
///
/// Returns NULL on failure, with [`sweetmtl_last_error`] saying why.
///
/// # Safety
///
/// `device` is a live device handle.
#[no_mangle]
pub unsafe extern "C" fn sweetmtl_device_new_buffer(
    device: *mut SweetMTLDevice,
    length: u64,
) -> *mut SweetMTLBuffer {
    guard(ptr::null_mut(), || {
        let Some(state) = (unsafe { SweetMTLDevice::state(device) }) else {
            set_last_error("sweetmtl_device_new_buffer: device is NULL");
            return ptr::null_mut();
        };
        match state.device().new_buffer(length, ResourceOptions::shared()) {
            Ok(buffer) => SweetMTLBuffer::make(BufferState { buffer }),
            Err(error) => {
                set_last_error(format!("new_buffer({length}) failed: {error}"));
                ptr::null_mut()
            }
        }
    })
}

